#!/bin/bash

set -ex

ROOT_BIN="$(cd ../.. && pwd)/node_modules/.bin"

# Names of all known functions, used by the templateIdentifier tokenizer to tell them from WITH template calls
{
  echo "// Generated by build.sh from the condFn<\"...\"> names in metricsql.grammar. Do not edit."
  echo "export const functionNames = new Set(["
  grep -o 'condFn<"[a-z_0-9]*">' src/metricsql.grammar | sed -E 's/condFn<("[a-z_0-9]*")>/\1/' | sort -u | sed -E 's/^(.*)$/  \1,/'
  echo "]);"
} > src/functionNames.js

"$ROOT_BIN/lezer-generator" src/metricsql.grammar -o src/parser

cat src/parser.terms.js >> src/parser.js

bash ./generate-types.sh

"$ROOT_BIN/rollup" -c
